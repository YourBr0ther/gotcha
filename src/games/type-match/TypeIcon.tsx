const PALETTE = { "#": "#1f1f24", w: "#ffffff" };

export function typeGlyph(type: TypeName): GlyphMap {
  return { rows: TYPE_ROWS[type], palette: PALETTE };
}

export function TypeIcon({ type, size }: { type: TypeName; size: number }) {
  return <PixelGlyph glyph={typeGlyph(type)} size={size} title={type} />;
}
